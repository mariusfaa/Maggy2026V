%% exportHILTimingForThesis.m
% =========================================================================
%  Export HIL timing MAT-files to thesis-ready CSV tables.
%
%  This script post-processes the output from:
%
%      hardwareNMPCController_HILTimingStudy.m
%
%  It intentionally keeps startup behaviour, steady-state averages, and
%  untrimmed steady-state tail metrics separate. The default steady-state
%  definition excludes the first 10 samples, which removes serial startup and
%  solver warm-up from average latency while preserving all remaining samples
%  for max, percentile, jitter, and deadline-miss analysis.
% =========================================================================

clearvars;
clc;

%% User configuration

scriptPath = mfilename('fullpath');

if ~isempty(scriptPath)
    scriptDir = fileparts(scriptPath);
    projectRoot = fileparts(fileparts(scriptDir));
else
    % This branch is useful when the file is executed as selected code or a
    % MATLAB Live Editor section, where mfilename can be empty.
    projectRoot = findProjectRootFrom(pwd);
end

resultsDir = fullfile(projectRoot, 'hil_timing_results');
csvDir     = fullfile(resultsDir, 'thesis_csv');

summaryFile = fullfile(resultsDir, 'hil_timing_summary.mat');

% Startup/warm-up samples excluded from the steady-state statistics.
steadyStateStartSample = 11;

% Optional descriptive statistic only. Do not use this for WCET or hard
% real-time claims.
trimUpperPercent = 1;

if ~exist(resultsDir, 'dir')
    projectRoot = findProjectRootFrom(pwd);
    resultsDir = fullfile(projectRoot, 'hil_timing_results');
    csvDir     = fullfile(resultsDir, 'thesis_csv');
    summaryFile = fullfile(resultsDir, 'hil_timing_summary.mat');
end

if ~exist(resultsDir, 'dir')
    error('Could not find hil_timing_results. Start from the MagLevTbx project or run this script file directly.');
end

if ~exist(csvDir, 'dir')
    [madeCsvDir, msg] = mkdir(csvDir);
    if ~madeCsvDir
        error('Could not create CSV output directory %s: %s', csvDir, msg);
    end
end

%% Load benchmark results

if exist(summaryFile, 'file')
    summaryInfo = dir(summaryFile);
    fprintf('Loading summary MAT-file:\n%s\n', summaryFile);
    fprintf('Summary timestamp: %s\n', summaryInfo.date);
    loaded = load(summaryFile, 'benchmarkResults');
    benchmarkResults = loaded.benchmarkResults;
else
    matFiles = dir(fullfile(resultsDir, 'hil_timing_N*.mat'));
    if isempty(matFiles)
        error('No HIL timing MAT-files found in %s.', resultsDir);
    end

    benchmarkResults = repmat(struct('stats', []), 1, numel(matFiles));
    for k = 1:numel(matFiles)
        loaded = load(fullfile(matFiles(k).folder, matFiles(k).name), 'stats');
        benchmarkResults(k).stats = loaded.stats;
    end
end

N_values = arrayfun(@(r) r.stats.N, benchmarkResults);
[~, order] = sort(N_values);
benchmarkResults = benchmarkResults(order);

%% Build CSV tables

nCases = numel(benchmarkResults);

metricsRows = cell(nCases, 1);
startupRows = {};
seriesFiles = strings(nCases, 1);

for k = 1:nCases
    stats = benchmarkResults(k).stats;

    sample = (1:numel(stats.t_total)).';
    total_ms = stats.t_total(:) * 1000;
    solve_ms = stats.t_solve(:) * 1000;
    io_ms = stats.t_io(:) * 1000;

    deadline_ms = stats.deadline_s * 1000;
    steadyIdx = sample >= steadyStateStartSample;
    startupIdx = ~steadyIdx;

    if ~any(steadyIdx)
        error('N=%d has no samples after steadyStateStartSample=%d.', ...
            stats.N, steadyStateStartSample);
    end

    rawTotal = total_ms;
    steadyTotal = total_ms(steadyIdx);
    steadySolve = solve_ms(steadyIdx);
    steadyIO = io_ms(steadyIdx);

    sortedSteady = sort(steadyTotal);
    nKeep = max(1, floor((1 - trimUpperPercent/100) * numel(sortedSteady)));
    trimmedSteady = sortedSteady(1:nKeep);

    seriesTable = table( ...
        sample, ...
        repmat(stats.N, numel(sample), 1), ...
        total_ms, ...
        solve_ms, ...
        io_ms, ...
        sample == 1, ...
        startupIdx, ...
        total_ms > deadline_ms, ...
        'VariableNames', { ...
            'Sample', ...
            'N', ...
            'Total_ms', ...
            'Solve_ms', ...
            'IO_ms', ...
            'IsFirstSample', ...
            'IsStartupWindow', ...
            'Miss_10ms'});

    seriesFile = sprintf('hil_timing_series_N%d.csv', stats.N);
    writetable(seriesTable, fullfile(csvDir, seriesFile));
    seriesFiles(k) = seriesFile;

    for i = find(startupIdx).'
        startupRows(end+1, :) = { ...
            stats.N, ...
            sample(i), ...
            total_ms(i), ...
            solve_ms(i), ...
            io_ms(i), ...
            total_ms(i) > deadline_ms}; %#ok<SAGROW>
    end

    metricsRows{k} = { ...
        stats.N, ...
        numel(sample), ...
        deadline_ms, ...
        steadyStateStartSample - 1, ...
        total_ms(1), ...
        solve_ms(1), ...
        io_ms(1), ...
        mean(rawTotal), ...
        median(rawTotal), ...
        max(rawTotal), ...
        std(rawTotal), ...
        prctile(rawTotal, 95), ...
        prctile(rawTotal, 99), ...
        100 * mean(rawTotal > deadline_ms), ...
        mean(steadyTotal), ...
        median(steadyTotal), ...
        max(steadyTotal), ...
        std(steadyTotal), ...
        prctile(steadyTotal, 90), ...
        prctile(steadyTotal, 95), ...
        prctile(steadyTotal, 99), ...
        100 * mean(steadyTotal > deadline_ms), ...
        mean(steadySolve), ...
        median(steadySolve), ...
        max(steadySolve), ...
        prctile(steadySolve, 99), ...
        mean(steadyIO), ...
        median(steadyIO), ...
        max(steadyIO), ...
        prctile(steadyIO, 99), ...
        mean(trimmedSteady)};
end

metricsTable = cell2table(vertcat(metricsRows{:}), ...
    'VariableNames', { ...
        'N', ...
        'Samples', ...
        'Deadline_ms', ...
        'StartupSamplesExcluded', ...
        'Startup_Total_ms', ...
        'Startup_Solve_ms', ...
        'Startup_IO_ms', ...
        'Raw_Mean_Total_ms', ...
        'Raw_Median_Total_ms', ...
        'Raw_WCET_Total_ms', ...
        'Raw_Jitter_ms', ...
        'Raw_P95_Total_ms', ...
        'Raw_P99_Total_ms', ...
        'Raw_MissRate_pct', ...
        'Steady_Mean_Total_ms', ...
        'Steady_Median_Total_ms', ...
        'Steady_Max_Total_ms', ...
        'Steady_Jitter_ms', ...
        'Steady_P90_Total_ms', ...
        'Steady_P95_Total_ms', ...
        'Steady_P99_Total_ms', ...
        'Steady_MissRate_pct', ...
        'Steady_Mean_Solve_ms', ...
        'Steady_Median_Solve_ms', ...
        'Steady_Max_Solve_ms', ...
        'Steady_P99_Solve_ms', ...
        'Steady_Mean_IO_ms', ...
        'Steady_Median_IO_ms', ...
        'Steady_Max_IO_ms', ...
        'Steady_P99_IO_ms', ...
        'Steady_TrimTop1pct_Mean_Total_ms'});

startupTable = cell2table(startupRows, ...
    'VariableNames', { ...
        'N', ...
        'Sample', ...
        'Total_ms', ...
        'Solve_ms', ...
        'IO_ms', ...
        'Miss_10ms'});

writetable(metricsTable, fullfile(csvDir, 'hil_timing_metrics.csv'));
writetable(startupTable, fullfile(csvDir, 'hil_timing_startup_window.csv'));

fprintf('\nExported HIL timing CSV files to:\n%s\n\n', csvDir);
fprintf('Steady-state statistics exclude samples 1-%d.\n', ...
    steadyStateStartSample - 1);
fprintf('Per-sample files:\n');
fprintf('  %s\n', seriesFiles);
fprintf('\nSummary metrics:\n');
disp(metricsTable(:, { ...
    'N', ...
    'Startup_Total_ms', ...
    'Steady_Mean_Total_ms', ...
    'Steady_Median_Total_ms', ...
    'Steady_P99_Total_ms', ...
    'Steady_Max_Total_ms', ...
    'Steady_MissRate_pct'}));

function projectRoot = findProjectRootFrom(startDir)
%FINDPROJECTROOTFROM Walk upward until the HIL timing result directory exists.

    projectRoot = '';
    currentDir = char(startDir);

    while true
        if exist(fullfile(currentDir, 'hil_timing_results'), 'dir')
            projectRoot = currentDir;
            return;
        end

        parentDir = fileparts(currentDir);

        if isempty(parentDir) || strcmp(parentDir, currentDir)
            break;
        end

        currentDir = parentDir;
    end

    error('Could not locate project root from %s.', startDir);
end
