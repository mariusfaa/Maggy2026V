function T = index_results(results_dir, varargin)
% INDEX_RESULTS  Walk a results tree and build a MATLAB table indexing
% every saved result_record.
%
%   T = index_results(results_dir)
%   T = index_results(results_dir, 'Save', true)
%
% Inputs
%   results_dir  root containing <stage>/<order>/*.mat files.
%   'Save'       logical (default false). When true, writes the table to
%                <results_dir>/_meta/index.mat alongside a json sidecar.
%
% Output T is a table with one row per result, with columns:
%   run_id, timestamp, schema_version, cfg_hash, params_hash, file,
%   stage, exp_id, order, N, Tf, dt,
%   integrator_type, sim_method_num_stages, sim_method_num_steps,
%   nlp_solver_type, qp_solver, hessian_approx, regularize_method,
%   alpha_we, warmstart_strategy,
%   asymmetric_plant, classification, reason,
%   n_actual, diverged, all_converged,
%   t_mean_ms, t_median_ms, t_p95_ms, t_p99_ms, t_max_ms, t_iqr_ms,
%   embedded_headroom_ms, embedded_feasible_p99, embedded_feasible_max,
%   J_integrated, settling_2pct_ms, peak_pos_mm, peak_ang_deg, peak_z_dev_mm,
%   final_err_norm, sqp_iter_mean, qp_iter_mean, pct_status_0,
%   has_disturbance, dist_recovery_time_ms, dist_max_z_deviation_post_mm,
%   dist_post_solve_time_spike_ms,
%   build_time_s, model_name
%
% Files that fail to load (corrupt, schema mismatch) are skipped with a
% printed warning; they do not abort the indexing.

    p = inputParser();
    p.addRequired('results_dir', @ischar);
    p.addParameter('Save', false, @islogical);
    p.parse(results_dir, varargin{:});

    files = dir(fullfile(results_dir, '*', '*', '*.mat'));
    if isempty(files)
        warning('index_results:no_files', 'No result files found under %s', results_dir);
        T = table();
        return
    end

    rows = cell(numel(files), 1);
    n_ok = 0;
    for i = 1:numel(files)
        fpath = fullfile(files(i).folder, files(i).name);
        try
            S = load(fpath, 'rec');
            r = row_from_record(S.rec, fpath);
            n_ok = n_ok + 1;
            rows{n_ok} = r;
        catch ME
            fprintf('[index_results] skipping %s: %s\n', fpath, ME.message);
        end
    end
    rows = rows(1:n_ok);
    if isempty(rows); T = table(); return; end

    T = struct2table(vertcat(rows{:}));

    if p.Results.Save
        meta_dir = fullfile(results_dir, '_meta');
        if ~exist(meta_dir,'dir'); mkdir(meta_dir); end
        save(fullfile(meta_dir, 'index.mat'), 'T', '-v7.3'); %#ok<NASGU>
    end
end

% ---------------------------------------------------------------------- %

function r = row_from_record(rec, fpath)
    cfg = rec.cfg;
    s   = rec.summary;
    bm  = rec.build_meta;

    r = struct( ...
        'run_id',         char_(rec.run_id), ...
        'timestamp',      char_(rec.timestamp), ...
        'schema_version', char_(rec.schema_version), ...
        'cfg_hash',       char_(rec.cfg_hash), ...
        'params_hash',    char_(rec.params_hash), ...
        'file',           char_(fpath), ...
        'stage',          char_(cfg.stage), ...
        'exp_id',         char_(cfg.exp_id), ...
        'order',          char_(cfg.order), ...
        'N',              cfg.N, ...
        'Tf',             cfg.Tf, ...
        'dt',             cfg.Tf / cfg.N, ...
        'integrator_type',          char_(cfg.integrator_type), ...
        'sim_method_num_stages',    cfg.sim_method_num_stages, ...
        'sim_method_num_steps',     cfg.sim_method_num_steps, ...
        'nlp_solver_type',          char_(cfg.nlp_solver_type), ...
        'qp_solver',                char_(cfg.qp_solver), ...
        'hessian_approx',           char_(cfg.hessian_approx), ...
        'regularize_method',        char_(cfg.regularize_method), ...
        'alpha_we',                 cfg.alpha_we, ...
        'warmstart_strategy',       char_(cfg.warmstart_strategy), ...
        'asymmetric_plant',         logical(getf_(bm, 'asymmetric_plant', false)), ...
        'classification',           char_(rec.classification), ...
        'reason',                   char_(rec.reason), ...
        'n_actual',                 s.n_actual, ...
        'diverged',                 logical(s.diverged), ...
        'all_converged',            logical(getf_(s, 'all_converged', false)), ...
        't_mean_ms',                getf_(s, 't_mean_ms', NaN), ...
        't_median_ms',              getf_(s, 't_median_ms', NaN), ...
        't_p95_ms',                 getf_(s, 't_p95_ms', NaN), ...
        't_p99_ms',                 getf_(s, 't_p99_ms', NaN), ...
        't_max_ms',                 getf_(s, 't_max_ms', NaN), ...
        't_iqr_ms',                 getf_(s, 't_iqr_ms', NaN), ...
        'embedded_headroom_ms',     getf_(s, 'embedded_headroom_ms', NaN), ...
        'embedded_feasible_p99',    logical(getf_(s, 'embedded_feasible_p99', false)), ...
        'embedded_feasible_max',    logical(getf_(s, 'embedded_feasible_max', false)), ...
        'J_integrated',             getf_(s, 'J_integrated', NaN), ...
        'settling_2pct_ms',         getf_(s, 'settling_2pct_ms', NaN), ...
        'peak_pos_mm',              getf_(s, 'peak_pos_mm', NaN), ...
        'peak_ang_deg',             getf_(s, 'peak_ang_deg', NaN), ...
        'peak_z_dev_mm',            getf_(s, 'peak_z_dev_mm', NaN), ...
        'final_err_norm',           getf_(s, 'final_err_norm', NaN), ...
        'sqp_iter_mean',            getf_(s, 'sqp_iter_mean', NaN), ...
        'qp_iter_mean',             getf_(s, 'qp_iter_mean', NaN), ...
        'pct_status_0',             getf_(s, 'pct_status_0', NaN), ...
        'has_disturbance',          logical(getf_(s, 'has_disturbance', false)), ...
        'dist_recovery_time_ms',    getf_(s, 'dist_recovery_time_ms', NaN), ...
        'dist_max_z_deviation_post_mm', getf_(s, 'dist_max_z_deviation_post_mm', NaN), ...
        'dist_post_solve_time_spike_ms', getf_(s, 'dist_post_solve_time_spike_ms', NaN), ...
        'build_time_s',             getf_(bm, 'build_time_s', NaN), ...
        'model_name',               char_(getf_(bm, 'model_name', '')) ...
    );
end

function v = getf_(s, fn, default_)
    if isfield(s, fn) && ~isempty(s.(fn)); v = s.(fn); else; v = default_; end
end

function c = char_(s)
    if isstring(s); c = char(s);
    elseif ischar(s); c = s;
    elseif isnumeric(s); c = num2str(s);
    else; c = ''; end
end
