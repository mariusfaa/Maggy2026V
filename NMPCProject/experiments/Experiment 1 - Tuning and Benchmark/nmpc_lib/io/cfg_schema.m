function S = cfg_schema()
% CFG_SCHEMA  Authoritative schema for experiment configurations.
%
%   S = cfg_schema()
%
% Returns a struct that describes every legal field of a cfg passed into
% the thesis framework. Used by validate_cfg() to enforce that no stage
% silently falls through to internal defaults.
%
% Each schema entry has fields:
%   .type        : 'numeric' | 'char' | 'logical' | 'struct' | 'cell' | 'function_handle'
%   .required    : true  -> caller must set;  false -> default applies
%   .default     : value used when .required = false and field is absent
%   .validator   : optional function_handle returning logical
%   .description : short human-readable string
%
% Sub-structs are nested (e.g., S.plant_override.integrator_type).
% Validation recurses into them.
%
% The schema is the single source of truth. To add a knob to the framework,
% add it here first, then teach build_ocp / build_plant / run_closed_loop
% to read it.

    f = @schema_field;

    S = struct();

    % --- 1. Identification (used in result path & filename) ----------
    S.stage   = f('char',   true,  [], @ischar, 'Stage identifier (e.g., "A", "B", "C1")');
    S.exp_id  = f('char',   true,  [], @ischar, 'Short experiment id, used in filename');
    S.order   = f('char',   true,  [], @(x) ismember(x,{'full12','reduced10'}), ...
                                          'Model order: "full12" or "reduced10"');

    % --- 2. Horizon ---------------------------------------------------
    S.N   = f('numeric', true, [], @(x) isscalar(x) && x>=1 && mod(x,1)==0, ...
                                       'Prediction horizon (shooting nodes)');
    S.Tf  = f('numeric', true, [], @(x) isscalar(x) && x>0, ...
                                       'Total prediction time (s); Ts = Tf/N');

    % --- 3. Integrator (drives plant defaults via matched-plant policy)
    S.integrator_type        = f('char',    true, [], ...
        @(x) ismember(x,{'ERK','IRK','GNSF'}), ...
        'acados OCP integrator type');
    S.sim_method_num_stages  = f('numeric', true, [], ...
        @(x) isscalar(x) && x>=1 && mod(x,1)==0, ...
        'Integrator stages (e.g., 4 for Gauss-Legendre IRK4)');
    S.sim_method_num_steps   = f('numeric', true, [], ...
        @(x) isscalar(x) && x>=1 && mod(x,1)==0, ...
        'Integrator substeps per shooting interval');

    % --- 4. NLP / QP / Hessian / regularize --------------------------
    S.nlp_solver_type    = f('char', true, [], ...
        @(x) ismember(x,{'SQP','SQP_RTI'}), ...
        'NLP solver type (SQP or real-time iteration)');
    S.qp_solver          = f('char', true, [], ...
        @(x) ismember(x,{'PARTIAL_CONDENSING_HPIPM','FULL_CONDENSING_HPIPM', ...
                         'FULL_CONDENSING_QPOASES','PARTIAL_CONDENSING_QPOASES'}), ...
        'acados QP solver');
    S.hessian_approx     = f('char', true, [], ...
        @(x) ismember(x,{'GAUSS_NEWTON','EXACT'}), ...
        'Hessian approximation');
    S.regularize_method  = f('char', true, [], ...
        @(x) ismember(x,{'NO_REGULARIZE','MIRROR','PROJECT','CONVEXIFY','PROJECT_REDUC_HESS'}), ...
        'Hessian regularization method');

    % --- 5. Cost ------------------------------------------------------
    %   Q, R supplied as diagonals (vectors) or full matrices.
    %   alpha_we is the terminal cost multiplier: W_e = alpha_we * Q.
    S.Q        = f('numeric', true, [], @(x) ~isempty(x) && (isvector(x) || ismatrix(x)), ...
                                       'Stage cost on states (vector = diag, or matrix)');
    S.R        = f('numeric', true, [], @(x) ~isempty(x) && (isvector(x) || ismatrix(x)), ...
                                       'Stage cost on inputs (vector = diag, or matrix)');
    S.alpha_we = f('numeric', true, [], @(x) isscalar(x) && x>=0, ...
                                       'Terminal cost multiplier: W_e = alpha_we * Q');

    % --- 6. Constraints ----------------------------------------------
    S.lbu     = f('numeric', true, [], @(x) isvector(x) && numel(x)==4, 'Input lower bounds (4)');
    S.ubu     = f('numeric', true, [], @(x) isvector(x) && numel(x)==4, 'Input upper bounds (4)');
    S.idxbx   = f('numeric', true, [], @(x) isvector(x) && all(x>=0),    'State-box indices (0-based, acados)');
    S.lbx     = f('numeric', true, [], @isvector,                          'State-box lower bounds');
    S.ubx     = f('numeric', true, [], @isvector,                          'State-box upper bounds');
    S.idxsbx  = f('numeric', true, [], @(x) isvector(x) && all(x>=0),    'Soft-constraint indices (0-based)');
    S.Zl      = f('numeric', true, [], @isvector, 'Slack quadratic penalty (lower)');
    S.Zu      = f('numeric', true, [], @isvector, 'Slack quadratic penalty (upper)');
    S.zl      = f('numeric', true, [], @isvector, 'Slack linear penalty (lower)');
    S.zu      = f('numeric', true, [], @isvector, 'Slack linear penalty (upper)');

    % --- 7. Closed-loop run ------------------------------------------
    S.sim_steps          = f('numeric', true, [], ...
        @(x) isscalar(x) && x>=1 && mod(x,1)==0, ...
        'Closed-loop step count');
    S.ic_descriptor      = f('struct',  true, [], @isstruct, ...
        ['Initial-condition descriptor: struct with fields .scale (numeric scalar) ' ...
         'and .direction (12-vector applied to xEq_plant; the framework projects to ' ...
         'controller-side as needed).']);
    S.warmstart_strategy = f('char', true, [], ...
        @(x) ismember(x,{'linear_to_eq','cold','shift_trajectory','previous_run'}), ...
        'Warm-start strategy');

    % --- 8. Optional (defaults applied) ------------------------------
    S.qp_solver_iter_max   = f('numeric', false, 200, ...
        @(x) isscalar(x) && x>=1 && mod(x,1)==0, 'QP iteration cap');
    S.qp_solver_warm_start = f('numeric', false, 1, ...
        @(x) ismember(x,[0 1 2]), 'QP warm-start flag (0|1|2)');
    S.nlp_solver_tol_stat  = f('numeric', false, 1e-4, @(x) isscalar(x) && x>0, 'NLP stationarity tol');
    S.nlp_solver_tol_eq    = f('numeric', false, 1e-4, @(x) isscalar(x) && x>0, 'NLP equality tol');
    S.nlp_solver_tol_ineq  = f('numeric', false, 1e-4, @(x) isscalar(x) && x>0, 'NLP inequality tol');
    S.nlp_solver_tol_comp  = f('numeric', false, 1e-4, @(x) isscalar(x) && x>0, 'NLP complementarity tol');
    S.nlp_solver_max_iter  = f('numeric', false, 50,  @(x) isscalar(x) && x>=1, ...
        'NLP iteration cap (forced to 1 internally when nlp_solver_type=SQP_RTI)');
    S.disturbance_schedule = f('struct', false, [], @(x) isempty(x) || isstruct(x), ...
        ['Disturbance schedule, or [] for none. Struct fields: .t_apply (s), ' ...
         '.kind ("state_additive"), .vector (12 elements applied to plant state).']);
    S.seed                 = f('numeric', false, 0, @(x) isscalar(x) && x>=0 && mod(x,1)==0, ...
        'Deterministic seed (used by LHS sweep in Stage G; 0 elsewhere)');
    S.allow_overwrite      = f('logical', false, false, @islogical, ...
        'If true, save_result overwrites an existing file with the same path');

    % --- 9. Plant override (matched-plant policy is the default) -----
    % If any plant_override.* field differs from the auto-derived value,
    % the result record gets asymmetric_plant=true and a plant_override_reason.
    po = struct();
    po.integrator_type        = f('char', false, '', ...
        @(x) isempty(x) || ismember(x,{'ERK','IRK','GNSF'}), ...
        'Plant integrator type; default = cfg.integrator_type');
    po.sim_method_num_stages  = f('numeric', false, [], ...
        @(x) isempty(x) || (isscalar(x) && x>=1 && mod(x,1)==0), ...
        'Plant integrator stages; default = cfg.sim_method_num_stages');
    po.sim_method_num_steps   = f('numeric', false, [], ...
        @(x) isempty(x) || (isscalar(x) && x>=1 && mod(x,1)==0), ...
        'Plant integrator substeps; default = cfg.sim_method_num_steps');
    po.magnet_n               = f('numeric', false, 10, ...
        @(x) isscalar(x) && x>=3 && mod(x,1)==0, ...
        'Plant magnet discretization (default 10 = baseline)');
    po.reason                 = f('char', false, '', @ischar, ...
        'Human-readable justification (required when any other plant_override.* is set)');
    S.plant_override = po;
end

function s = schema_field(type, required, default, validator, description)
    s = struct( ...
        'type',        type, ...
        'required',    logical(required), ...
        'default',     default, ...
        'validator',   validator, ...
        'description', description ...
    );
end
