"""Pareto plots and top-K tables from index.csv.

Usage:
    python plot_pareto.py [--results-dir PATH]

Reads:  <results-dir>/index.csv
Writes: <results-dir>/figs/pareto_<model_kind>_<stage>.pdf
        <results-dir>/figs/top3_<model_kind>.tex
"""
from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd


def pareto_front(df: pd.DataFrame, x: str, y: str) -> pd.DataFrame:
    """Return the subset of rows that are not dominated in (x, y) (lower=better)."""
    pts = df[[x, y]].to_numpy()
    n = len(pts)
    keep = []
    for i in range(n):
        dominated = False
        for j in range(n):
            if i == j:
                continue
            if (
                pts[j, 0] <= pts[i, 0]
                and pts[j, 1] <= pts[i, 1]
                and (pts[j, 0] < pts[i, 0] or pts[j, 1] < pts[i, 1])
            ):
                dominated = True
                break
        if not dominated:
            keep.append(i)
    return df.iloc[keep].sort_values(x)


def plot_one(df: pd.DataFrame, model_kind: str, stages: list[str], out: Path) -> None:
    sub = df[(df.model_kind == model_kind) & df.stage.isin(stages)].copy()
    if sub.empty:
        print(f"  (no rows for {model_kind} stages {stages}; skipping)")
        return
    sub = sub[~sub.diverged & sub.all_converged].copy()
    if sub.empty:
        print(f"  (all runs for {model_kind} {stages} diverged or unconverged; skipping)")
        return

    fig, ax = plt.subplots(figsize=(7.0, 4.5))
    for stage, marker in zip(stages, ["o", "s", "^", "D", "P"]):
        s = sub[sub.stage == stage]
        if s.empty:
            continue
        sc = ax.scatter(
            s.t_mean_ms,
            s.J_integrated,
            label=f"stage {stage}",
            marker=marker,
            s=55,
            alpha=0.75,
            edgecolors="k",
            linewidths=0.5,
        )

    front = pareto_front(sub, "t_mean_ms", "J_integrated")
    ax.plot(
        front.t_mean_ms,
        front.J_integrated,
        "--",
        color="black",
        alpha=0.5,
        label="Pareto front",
    )

    # Real-time deadline line (dt = Tf/N) — annotate the nominal Stage 1b dt
    # if available, otherwise skip the line.
    dt_ref = sub[sub.stage == "1b"].dt.median() if (sub.stage == "1b").any() else sub.dt.median()
    if pd.notna(dt_ref):
        ax.axvline(dt_ref * 1000, color="red", linestyle=":", linewidth=1.2,
                   label=f"deadline {dt_ref*1000:.1f} ms")

    ax.set_xlabel("Mean per-step solve time [ms]")
    ax.set_ylabel("Closed-loop integrated cost J")
    ax.set_title(f"Pareto: {model_kind}  ({', '.join(stages)})")
    ax.set_yscale("log")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(loc="best", fontsize=9)
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)
    print(f"  wrote {out}")


def write_top3_table(df: pd.DataFrame, model_kind: str, out: Path) -> None:
    sub = df[(df.model_kind == model_kind) & (df.stage == "1b")].copy()
    sub = sub[~sub.diverged & sub.all_converged].copy()
    if sub.empty:
        print(f"  (no top-3 candidates for {model_kind})")
        return
    front = pareto_front(sub, "t_mean_ms", "J_integrated")
    front = front.sort_values("J_integrated").head(3)

    rows = []
    for _, r in front.iterrows():
        rows.append(
            f"{r.exp_id} & {r.integ_type} & {r.nlp_solver} & {r.qp_solver.split('_')[0]} & "
            f"{r.hessian_approx} & {r.t_mean_ms:.2f} & {r.t_max_ms:.2f} & {r.J_integrated:.3e} \\\\"
        )

    body = "\n    ".join(rows)
    tex = f"""% Auto-generated by plot_pareto.py
\\begin{{tabular}}{{lccccccc}}
\\toprule
exp\\_id & integrator & NLP & QP & Hessian & $\\bar{{t}}$ [ms] & $t_{{\\max}}$ [ms] & $J$ \\\\
\\midrule
    {body}
\\bottomrule
\\end{{tabular}}
"""
    out.write_text(tex)
    print(f"  wrote {out}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results-dir", type=Path, default=Path("results"))
    args = ap.parse_args()

    csv = args.results_dir / "index.csv"
    if not csv.exists():
        raise SystemExit(f"index.csv not found at {csv}; run dump_index() first")

    df = pd.read_csv(csv)
    # `diverged` and `all_converged` are written as 0/1 ints by dump_index.m.
    # Cast to bool so `~df.diverged & df.all_converged` yields a proper
    # boolean mask (otherwise pandas treats the int result as column indices
    # and raises KeyError).
    for col in ("diverged", "all_converged"):
        if col in df.columns:
            df[col] = df[col].astype(bool)
    figs = args.results_dir / "figs"
    figs.mkdir(parents=True, exist_ok=True)

    for model_kind in df.model_kind.unique():
        plot_one(df, model_kind, ["1b"],         figs / f"pareto_{model_kind}_1b.pdf")
        plot_one(df, model_kind, ["1b", "2"],    figs / f"pareto_{model_kind}_1b2.pdf")
        plot_one(df, model_kind, ["2"],          figs / f"pareto_{model_kind}_2.pdf")
        write_top3_table(df, model_kind,         figs / f"top3_{model_kind}.tex")


if __name__ == "__main__":
    main()
