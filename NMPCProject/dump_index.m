function dump_index(results_dir)
% DUMP_INDEX  Walk results/ and emit index.csv with one row per .mat file.
%
%   dump_index()                              % default: NMPCProject/results
%   dump_index('path/to/results')

    if nargin < 1 || isempty(results_dir)
        paths = project_setup();
        results_dir = fullfile(paths.project_root, 'results');
    end
    if ~exist(results_dir, 'dir')
        error('dump_index: directory not found: %s', results_dir);
    end

    files = list_mat_files(results_dir);
    if isempty(files)
        warning('dump_index: no .mat files under %s', results_dir);
        return;
    end

    csv_path = fullfile(results_dir, 'index.csv');
    fid = fopen(csv_path, 'w');
    if fid < 0; error('Cannot open %s for writing.', csv_path); end

    header = strjoin({ ...
        'run_id','timestamp','model_kind','stage','exp_id', ...
        'controller_n','plant_n', ...
        'integ_type','n_stages','n_steps', ...
        'nlp_solver','qp_solver','hessian_approx', ...
        'N','Tf','dt','alpha_R','alpha_we', ...
        'ic_label','ic_scale','n_repeats', ...
        'n_actual','diverged','all_converged', ...
        't_mean_ms','t_p95_ms','t_p99_ms','t_max_ms', ...
        't_wall_mean_ms','t_wall_p99_ms','t_wall_max_ms', ...
        'J_integrated', ...
        'settling_1pct_ms','settling_5pct_ms', ...
        'peak_pos_mm','peak_ang_deg','peak_yaw_deg','peak_z_dev_mm', ...
        'control_effort','pct_saturated', ...
        'n_hard_viol','max_hard_viol','compile_time_s', ...
        'sqp_iter_mean','qp_iter_mean','filepath' }, ',');
    fprintf(fid, '%s\n', header);

    n_rows = 0;
    for k = 1:length(files)
        try
            s = load(files(k).path);
            sm = s.summary;
            row = sprintf(['%s,%s,%s,%s,%s,', ...
                           '%d,%d,', ...
                           '%s,%d,%d,', ...
                           '%s,%s,%s,', ...
                           '%d,%.6f,%.6f,%g,%g,', ...
                           '%s,%g,%d,', ...
                           '%g,%d,%d,', ...
                           '%g,%g,%g,%g,', ...
                           '%g,%g,%g,', ...
                           '%g,', ...
                           '%g,%g,', ...
                           '%g,%g,%g,%g,', ...
                           '%g,%g,', ...
                           '%d,%g,%g,', ...
                           '%g,%g,"%s"\n'], ...
                s.run_id, s.timestamp, s.model_kind, s.stage, s.exp_id, ...
                s.controller_n, s.plant_n, ...
                s.integ_type, s.n_stages, s.n_steps, ...
                s.nlp_solver, s.qp_solver, s.hessian_approx, ...
                s.N, s.Tf, s.dt, getfdef(s,'alpha_R',NaN), s.alpha_we, ...
                s.ic_label, s.ic_scale, s.n_repeats, ...
                sm.n_actual, sm.diverged, sm.all_converged, ...
                sm.t_mean_ms, sm.t_p95_ms, sm.t_p99_ms, sm.t_max_ms, ...
                sm.t_wall_mean_ms, sm.t_wall_p99_ms, sm.t_wall_max_ms, ...
                sm.J_integrated, ...
                sm.settling_1pct_ms, sm.settling_5pct_ms, ...
                sm.peak_pos_mm, sm.peak_ang_deg, sm.peak_yaw_deg, sm.peak_z_dev_mm, ...
                sm.control_effort, sm.pct_saturated, ...
                sm.n_hard_viol, sm.max_hard_viol, getfdef(sm,'compile_time_s',NaN), ...
                sm.sqp_iter_mean, sm.qp_iter_mean, files(k).path);
            fprintf(fid, '%s', row);
            n_rows = n_rows + 1;
        catch ME
            fprintf(2, 'dump_index: skipped %s (%s)\n', files(k).path, ME.message);
        end
    end
    fclose(fid);
    fprintf('Wrote %d rows to %s\n', n_rows, csv_path);
end

function files = list_mat_files(root)
    files = struct('path', {});
    sub = dir(fullfile(root, '*'));
    for k = 1:length(sub)
        if ~sub(k).isdir; continue; end
        if startsWith(sub(k).name, '.'); continue; end
        if strcmp(sub(k).name, '_checkpoints'); continue; end
        % Each model_kind dir; walk its stages
        stages = dir(fullfile(sub(k).folder, sub(k).name));
        for j = 1:length(stages)
            if ~stages(j).isdir; continue; end
            if startsWith(stages(j).name, '.'); continue; end
            mats = dir(fullfile(stages(j).folder, stages(j).name, '*.mat'));
            for i = 1:length(mats)
                files(end+1).path = fullfile(mats(i).folder, mats(i).name); %#ok<AGROW>
            end
        end
    end
end

function v = getfdef(s, f, d)
    if isfield(s, f) && ~isempty(s.(f)); v = s.(f); else; v = d; end
end
